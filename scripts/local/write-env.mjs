#!/usr/bin/env node
/**
 * Write local-only env files for the harness.
 *
 * Browser env: .env.local (gitignored)
 * Edge-function env: supabase/functions/.env.local (gitignored)
 *
 * This script only uses the local Supabase keys printed by `supabase status`.
 * It never reads or writes production keys.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const marker = '# Generated by scripts/local/write-env.mjs — local harness only.';

function statusEnv() {
  const raw = execFileSync('supabase', ['status', '-o', 'env'], {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  const values = {};
  for (const line of raw.split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (!match) continue;
    values[match[1]] = match[2].replace(/^['"]|['"]$/g, '');
  }
  return values;
}

function productionAppId() {
  const file = path.join(root, '.env.production');
  if (!fs.existsSync(file)) return '';
  const text = fs.readFileSync(file, 'utf8');
  const match =
    text.match(/^VITE_PRIVY_APP_ID=(.+)$/m) ??
    text.match(/^PRIVY_APP_ID=(.+)$/m);
  return match ? match[1].trim() : '';
}

function backupUnmanaged(file) {
  if (!fs.existsSync(file)) return;
  const text = fs.readFileSync(file, 'utf8');
  if (text.includes(marker)) return;
  const backup = `${file}.before-local-harness`;
  fs.copyFileSync(file, backup);
  console.warn(`Backed up existing ${path.relative(root, file)} to ${path.relative(root, backup)}`);
}

const status = statusEnv();
const apiUrl = status.API_URL;
const anonKey = status.ANON_KEY ?? status.PUBLISHABLE_KEY;
const appId = productionAppId();

if (!apiUrl || !anonKey) {
  console.error('Could not read local Supabase URL/key from `supabase status -o env`.');
  console.error('Is the local stack running? Try: npm run local:start');
  process.exit(1);
}
if (!/^https?:\/\/(127\.0\.0\.1|localhost|\[::1\])(:\d+)?$/i.test(apiUrl)) {
  console.error(`Refusing non-local Supabase URL: ${apiUrl}`);
  process.exit(1);
}
if (!appId) {
  console.error('Could not find VITE_PRIVY_APP_ID / PRIVY_APP_ID in .env.production.');
  console.error('Copy the public Privy app id into .env.production before running the local harness.');
  process.exit(1);
}

const browserEnv = `${marker}
# Do not use these values in production. They point at the local Supabase stack.
VITE_SUPABASE_URL=${apiUrl}
VITE_SUPABASE_PUBLISHABLE_KEY=${anonKey}
VITE_SUPABASE_PROJECT_ID=local
VITE_PRIVY_APP_ID=${appId}
VITE_LOCAL_TEST_MODE=true
`;

const functionsEnv = `${marker}
# Only the supabase functions serve --env-file command reads this file.
LOCAL_TEST_MODE=true
PUBLIC_APP_URL=http://localhost:8080
ALLOW_LOCAL_CHECKOUT=true
`;

const browserFile = path.join(root, '.env.local');
const functionsFile = path.join(root, 'supabase/functions/.env.local');
backupUnmanaged(browserFile);
backupUnmanaged(functionsFile);
fs.writeFileSync(browserFile, browserEnv);
fs.writeFileSync(functionsFile, functionsEnv);

console.log(`Wrote ${path.relative(root, browserFile)} and ${path.relative(root, functionsFile)}`);
console.log(`Local API: ${apiUrl}`);
